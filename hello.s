// Исправленный вариант для macOS ARM64
.global _start          // Делаем метку _start видимой для линкера
.align 2                // Выравнивание

_start:
    // 1. Пишем в стандартный вывод (stdout = 1)
    mov x0, #1          // file descriptor: 1 (stdout)
    
    // Вместо adr используем adrp + add для загрузки адреса (корректно для macOS)
    adrp x1, msg@PAGE    // Загружаем страницу адреса msg
    add x1, x1, msg@PAGEOFF // Добавляем смещение в странице
    
    mov x2, #13         // длина строки (13 байт)
    mov x16, #4         // номер системного вызова "write" в macOS
    svc #0x80           // выполняем системный вызов

    // 2. Корректно завершаем программу
    mov x0, #0          // код возврата: 0 (успех)
    mov x16, #1         // номер системного вызова "exit"
    svc #0x80           // выполняем системный вызов

// Помещаем данные в секцию данных
.data
msg:
    .ascii "Hello, ARM!\n"  // Сама строка